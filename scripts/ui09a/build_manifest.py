#!/usr/bin/env python3
"""Index UI-09-A screenshots without relabelling synthetic states as real AI processing."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct

MODES = ['light-font100', 'dark-font100', 'light-font160', 'dark-font160']
SCREENS = [
    'video-empty', 'jobs-empty', 'jobs-state-first-page', 'jobs-state-second-page',
    'results-with-real-video', 'editor-with-27-cues', 'editor-cue-second-page',
    'results-without-video', 'editor-without-video', 'settings-collapsed',
    'settings-expanded', 'jobs-seeded-running-status-no-worker',
]
NATIVE = ['on-device', 'cloud-live', 'vosk-local']


def png_record(path, folder):
    data = path.read_bytes()
    if len(data) < 1024 or data[:8] != b'\x89PNG\r\n\x1a\n' or data[12:16] != b'IHDR':
        raise ValueError('Screenshot missing or not a valid PNG: ' + path.name)
    width, height = struct.unpack('>II', data[16:24])
    if min(width, height) < 320:
        raise ValueError('Screenshot unreasonably small: ' + path.name)
    return {
        'relativePath': str(path.relative_to(folder)).replace('\\', '/'),
        'width': width, 'height': height, 'sizeBytes': len(data),
        'sha256': hashlib.sha256(data).hexdigest(),
    }


def build_device(root):
    screens = []
    for combo in MODES:
        for name in SCREENS:
            path = root / 'device' / (name + '-' + combo + '.png')
            if not path.is_file():
                raise FileNotFoundError('Missing Android device screenshot: ' + str(path))
            item = png_record(path, root)
            item['scenario'] = name
            item['configuration'] = combo
            item['sourceType'] = 'Android 15 API35 device emulator, actual running app'
            item['dataKind'] = 'deterministic on-device QA fixtures'
            screens.append(item)
        for native in NATIVE:
            theme = combo.split('-')[0]
            path = root / 'native' / combo / (native + '-' + theme + '.png')
            if not path.is_file():
                raise FileNotFoundError('Missing native screenshot: ' + str(path))
            item = png_record(path, root)
            item['scenario'] = native
            item['configuration'] = combo
            item['sourceType'] = 'Android 15 API35 native screen, actual running app'
            item['dataKind'] = 'initial state: no microphone recording, no model download'
            screens.append(item)
    assert len(screens) == 60
    return screens


def build_web(root):
    groups = [
        'web/editorial-4a',
        'web/editorial-2-2b',
        'web/editorial-2-2d',
    ]
    screens = []
    for group in groups:
        folder = root / group
        files = sorted(folder.glob('*.png'))
        if len(files) < 4:
            raise ValueError('Expected 4+ Chromium screenshots in ' + group)
        for path in files:
            record = png_record(path, root)
            record['sourceType'] = 'Chromium Playwright UI with deterministic QA data, not Android hardware'
            record['scenario'] = group.split('/')[-1]
            screens.append(record)
    if not screens:
        raise ValueError('No Chromium baseline screenshots')
    return screens


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--mode', choices=['device', 'web'], required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    screens = build_device(root) if args.mode == 'device' else build_web(root)
    manifest = {
        'work': 'UI-09-A',
        'scope': args.mode,
        'sourceSHA': os.environ.get('CAPTURE_SOURCE_SHA') or os.environ.get('GITHUB_SHA', ''),
        'githubRunId': os.environ.get('GITHUB_RUN_ID'),
        'api': 35 if args.mode == 'device' else None,
        'screenshots': screens,
        'screenCount': len(screens),
        'provenance': {
            'android': 'Actual app running on Android 15 Pixel 6 emulator; MediaStore contains a generated playable MP4 fixture, 27 subtitle cues, a 15-cue SRT-only import, and disposable prepared/paused/error JobStore records',
            'video': 'Generated by ffmpeg testsrc2; not a user video and never transmitted externally',
            'running': 'UI status is seeded running AFTER app launch with no processing service; not evidence of actual transcription progress or network activity',
            'errors': 'QA-only injected error text, not a recorded failure of a real provider',
            'web': 'Browser tests use Chromium Playwright with mock Native Bridge / deterministic fixtures. Not an Android screenshot.',
            'native': 'Initial native recognition screens; no actual microphone, paid model, or Vosk download run',
        },
        'notTested': [
            'Physical smartphone TalkBack or IME',
            'Real paid API inference or speech quality',
            'Real model installation, Vosk transcription performance',
            'Real-time audio processing throughput or 0-100% progress',
            'Google Play Console review, approval or tester visibility',
        ],
    }
    manifest_path = root / ('device-provenance.json' if args.mode == 'device' else 'web-provenance.json')
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'UI-09-A: {len(screens)} {args.mode} screenshots verified (PNG+SHA256).')
    print('No Play store update, audio transcription, real API calls, or production app state changes.')


if __name__ == '__main__':
    main()
